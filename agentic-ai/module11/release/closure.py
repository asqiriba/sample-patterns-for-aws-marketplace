"""Import closures: one list is both what is hashed and what ships.

`closure(entry, repo_root)` runs modulefinder over the entry script (function bodies too, so
lazy imports are captured), keeps only modules inside the repo, adds every package
`__init__.py` on the way, and returns sorted repo-relative paths. The committed lists live in
`module11/harness/pipeline/closures/`; check C12 regenerates and compares them.
"""
from __future__ import annotations

import io
import modulefinder
import re
import zipfile
from pathlib import Path

CLOSURES_DIR = "module11/harness/pipeline/closures"
TOOLS_DIR = "module11/harness/agent/tools"
RUNTIME_ENTRY = "module11/runtime/app.py"
HEADER = "# Generated by `python -m module11 closure update`; check C12 fails when stale.\n"
EDGE_HEADER = ("# Hand-maintained edge closure: `<repo path>` or `<repo path> as <zip name>`.\n"
               "# Check C12 resolves every `from \"./x.mjs\"` import against the zip names.\n")
FIXED_TIME = (1980, 1, 1, 0, 0, 0)
_SKIP_PARTS = {"__pycache__", ".pytest_cache"}


def _rel(path: Path, root: Path) -> str | None:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return None


def _package_module(entry_path: Path, root: Path) -> str | None:
    """`module11.release.rollout_sim` for a file whose directories up to the repo root are all
    packages; None for a script outside a package (handler/index.py)."""
    rel = _rel(entry_path, root)
    if rel is None or entry_path.name == "__init__.py":
        return None
    parts = Path(rel).with_suffix("").parts
    for depth in range(1, len(parts)):
        if not (root / Path(*parts[:depth]) / "__init__.py").is_file():
            return None
    return ".".join(parts) if len(parts) > 1 else None


def closure(entry: str | Path, repo_root: str | Path, extra_path: list[str] | None = None) -> list[str]:
    """Repo-relative files the entry script imports, transitively, plus package __init__ files."""
    root = Path(repo_root)
    entry_path = Path(entry) if Path(entry).is_absolute() else root / entry
    if not entry_path.is_file():
        return []
    search = [str(p) for p in (extra_path or [])] + [str(root)]
    finder = modulefinder.ModuleFinder(path=search)
    dotted = _package_module(entry_path, root)
    if dotted:
        # A module inside a package (relative imports allowed): import it by its dotted name.
        finder.import_hook(dotted)
    else:
        finder.run_script(str(entry_path))
    files: set[str] = set()
    entry_rel = _rel(entry_path, root)
    if entry_rel:
        files.add(entry_rel)
    for module in finder.modules.values():
        filename = getattr(module, "__file__", None)
        if not filename:
            continue
        rel = _rel(Path(filename), root)
        if rel is None or not rel.endswith(".py"):
            continue
        files.add(rel)
        # Package __init__ files: modulefinder records each imported package as a module whose
        # file is its __init__.py; add them explicitly for dotted names it reached only by path.
        parts = module.__name__.split(".")
        if len(parts) > 1:
            pkg_dir = Path(rel).parent if not rel.endswith("__init__.py") else Path(rel).parent.parent
            for _ in parts[:-1]:
                init = pkg_dir / "__init__.py"
                if (root / init).is_file():
                    files.add(init.as_posix())
                pkg_dir = pkg_dir.parent
    return sorted(files)


def _walk(root: Path, rel_dir: str) -> list[str]:
    base = root / rel_dir
    if not base.is_dir():
        return []
    return sorted(p.relative_to(root).as_posix() for p in base.rglob("*")
                  if p.is_file() and not (_SKIP_PARTS & set(p.parts)) and p.suffix != ".pyc")


def handler_closure(tool: str, repo_root: str | Path) -> list[str]:
    """`handler/index.py`'s closure plus every file under `handler/`."""
    root = Path(repo_root)
    handler_dir = f"{TOOLS_DIR}/{tool}/handler"
    entry = root / handler_dir / "index.py"
    files = set(closure(entry, root, extra_path=[str(root / handler_dir)])) | set(_walk(root, handler_dir))
    return sorted(files)


def lambda_tools(repo_root: str | Path) -> list[str]:
    root = Path(repo_root) / TOOLS_DIR
    if not root.is_dir():
        return []
    return sorted(p.parent.parent.name for p in root.glob("*/handler/index.py"))


def expected_closures(repo_root: str | Path) -> dict[str, list[str]]:
    """Generated closure lists keyed by file name (runtime.txt, handler-<tool>.txt)."""
    root = Path(repo_root)
    lists = {"runtime.txt": closure(root / RUNTIME_ENTRY, root)}
    for tool in lambda_tools(root):
        lists[f"handler-{tool}.txt"] = handler_closure(tool, root)
    return lists


def parse_list(text: str) -> list[str]:
    return [line.strip() for line in text.splitlines() if line.strip() and not line.lstrip().startswith("#")]


def render_list(paths: list[str]) -> str:
    return HEADER + "".join(f"{p}\n" for p in paths)


def read_list(repo_root: str | Path, name: str) -> list[str] | None:
    path = Path(repo_root) / CLOSURES_DIR / name
    return parse_list(path.read_text(encoding="utf-8")) if path.is_file() else None


def update(repo_root: str | Path) -> list[str]:
    """Rewrite the generated closure lists; returns the names that changed."""
    root = Path(repo_root)
    out_dir = root / CLOSURES_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    changed = []
    wanted = expected_closures(root)
    for name, paths in wanted.items():
        target = out_dir / name
        text = render_list(paths)
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
            changed.append(name)
    for stale in out_dir.glob("handler-*.txt"):
        if stale.name not in wanted:
            stale.unlink()
            changed.append(stale.name)
    edge = out_dir / "edge.txt"
    if not edge.is_file():
        edge.write_text(EDGE_HEADER, encoding="utf-8")
        changed.append("edge.txt")
    return sorted(changed)


def stale(repo_root: str | Path) -> list[str]:
    """Names of committed closure lists that differ from a regeneration (C12)."""
    root = Path(repo_root)
    wanted = expected_closures(root)
    bad = [name for name, paths in wanted.items() if read_list(root, name) != paths]
    present = {p.name for p in (root / CLOSURES_DIR).glob("handler-*.txt")}
    bad += sorted(present - set(wanted))
    return sorted(bad)


# ---------------------------------------------------------------- edge closure
_MJS_IMPORT = re.compile(r"""(?:import|export)\s[^'"]*?from\s+['"](\./[^'"]+)['"]|import\s*\(\s*['"](\./[^'"]+)['"]\s*\)""")


def edge_entries(repo_root: str | Path) -> list[tuple[str, str]]:
    """[(repo path, zip name)] from edge.txt."""
    listed = read_list(repo_root, "edge.txt") or []
    entries = []
    for line in listed:
        parts = line.split(" as ")
        path = parts[0].strip()
        name = parts[1].strip() if len(parts) > 1 else Path(path).name
        entries.append((path, name))
    return entries


def edge_problems(repo_root: str | Path) -> list[str]:
    root = Path(repo_root)
    entries = edge_entries(root)
    names = {name for _, name in entries}
    problems = []
    for path, _ in entries:
        file = root / path
        if not file.is_file():
            problems.append(f"edge.txt lists a missing file: {path}")
            continue
        for match in _MJS_IMPORT.finditer(file.read_text(encoding="utf-8")):
            target = (match.group(1) or match.group(2))[2:]
            if target not in names:
                problems.append(f"{path} imports ./{target}, which edge.txt does not list")
    return problems


def edge_files(repo_root: str | Path) -> list[str]:
    return sorted(path for path, _ in edge_entries(repo_root))


# ---------------------------------------------------------------- deterministic zips
def deterministic_zip(members: list[tuple[str, bytes]]) -> bytes:
    """Sorted entries, fixed timestamps, mode 0644: the same bytes on every machine."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in sorted(members):
            info = zipfile.ZipInfo(name, date_time=FIXED_TIME)
            info.external_attr = 0o100644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data)
    return buffer.getvalue()


def handler_zip_members(tool: str, repo_root: str | Path) -> list[tuple[str, str]]:
    """[(zip name, repo path)]: handler/* at the zip root, everything else at its repo path."""
    prefix = f"{TOOLS_DIR}/{tool}/handler/"
    files = read_list(repo_root, f"handler-{tool}.txt") or handler_closure(tool, repo_root)
    return sorted((p[len(prefix):] if p.startswith(prefix) else p, p) for p in files)


def handler_zip(tool: str, repo_root: str | Path) -> bytes:
    root = Path(repo_root)
    return deterministic_zip([(name, (root / path).read_bytes())
                              for name, path in handler_zip_members(tool, root)])
